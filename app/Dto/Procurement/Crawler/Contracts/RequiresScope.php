<?php

declare(strict_types=1);

namespace App\Dto\Procurement\Crawler\Contracts;

/**
 * Структурная гарантия против профиля-«всё подряд»: фильтр, отмеченный этим контрактом, обязан
 * нести непустой предметный скоуп, иначе профиль не сохраняется (`Crawler::saving()`, D18).
 * Существует потому, что мягкий вариант измерен: то же окно дат без ОКПД2 даёт 22 761 закупку
 * против 1 233 с фильтром `43` (`findings/P1-okpd2-probe.md` §3) — случайно сохранённый профиль
 * без скоупа молча расширяет выборку почти в 18 раз и жжёт бюджет запросов к площадке.
 *
 * Контракт, а не `if ($registry->code === 'fz44')` в модели: проверка по коду реестра прямо
 * запрещена каноном этой ветки кода (`CrawlerForm` docblock). Один реализующий класс сегодня
 * (`EisSearchFilter`) — гипотетический шов, поэтому интерфейс узкий, без задела.
 */
interface RequiresScope
{
    /**
     * Несёт ли фильтр хотя бы одно значение предметного скоупа. Смысл «скоупа» принадлежит
     * реализации: у ЕИС это выбранные узлы ОКПД2.
     */
    public function hasScope(): bool;
}
