<?php

declare(strict_types=1);

namespace App\Services\Procurement\Contracts;

/**
 * Опциональный контракт валидации `type_profile` (§1.6 контракта P2.1, D132) — ВТОРОЙ
 * представитель механизма опциональных capability-интерфейсов (§1.5, D106): анализатор типа
 * владеет схемой профиля и её проверкой (§6.1/§6.2 root/document-type-axis.md), ядро/витрина
 * только спрашивают `instanceof` — тип без реализации ничего не проверяет, это штатная ветка,
 * не отказ.
 *
 * Возврат — ДАННЫЕ об ошибках, а не схема формы и не набор правил валидатора: ключ — поле профиля
 * (`class`, `form`, …) либо пустая строка `''` для ошибки профиля целиком, значение — список
 * готовых к показу сообщений; пустой массив = профиль валиден. Метод получает СЫРОЙ массив профиля
 * и НЕ бросает на невалидном профиле — невалидность его ПРЕДМЕТ, а не исключительная ситуация;
 * проверка ПОЛНАЯ (все поля разом, не до первой ошибки).
 */
interface SupportsTypeProfileValidation
{
    /**
     * @param  array<string, mixed>  $profile
     * @return array<string, list<string>>
     */
    public function validateTypeProfile(array $profile): array;
}
